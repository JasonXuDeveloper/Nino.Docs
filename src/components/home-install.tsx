/**
 * The home page's install box: one command per platform (.NET, Unity, and the
 * Go, Rust and TypeScript runtimes of the code nino-gen generates) behind a
 * segmented switch, and the line for AI coding agents. Every panel is in the
 * prerendered HTML (all but the selected one hidden), so crawlers read every
 * command and a reader without JavaScript still gets the .NET one. The
 * commands are those of the Quick Start, Unity and codegen pages and Nino's
 * runtime READMEs.
 */
import { Bot, Check, Copy } from 'lucide-react';
import { useState } from 'react';
import { Link } from 'react-router';
import { Segmented } from '@/components/showcase';
import type { Locale } from '@/lib/i18n';

type Platform = 'dotnet' | 'unity' | 'go' | 'rust' | 'typescript';

interface Panel {
  value: Platform;
  label: string;
  commands: string[];
  note: string;
  /** Path under the docs root, for the note's link */
  href: string;
  link: string;
}

const generated = {
  en: 'Generated by nino-gen from your C# [NinoType]s; the runtime is published with every release from 4.0.0-rc.8.',
  zh: '代码由 nino-gen 从你的 C# [NinoType] 生成；运行时从 4.0.0-rc.8 起随每个版本发布。',
};

function panels(lang: Locale): Panel[] {
  const zh = lang === 'zh';
  const codegen = zh ? '生成代码' : 'Generating the code';
  return [
    {
      value: 'dotnet',
      label: '.NET',
      commands: ['dotnet add package Nino --prerelease'],
      note: zh
        ? '任何 .NET 项目，包括 Godot 4。v4 还是预发行版，必须加 --prerelease。'
        : 'Any .NET project, Godot 4 included. v4 is a prerelease, so --prerelease is required.',
      href: 'start',
      link: zh ? '快速开始' : 'Quick Start',
    },
    {
      value: 'unity',
      label: 'Unity',
      commands: ['openupm add com.jasonxudeveloper.nino'],
      note: zh
        ? 'Unity 2022.3 及以上，来自 OpenUPM：生成器和 Unity 格式化器在同一个包里。'
        : 'Unity 2022.3 or later, from OpenUPM: the generator and the Unity formatters in one package.',
      href: 'advanced/unity',
      link: 'Unity',
    },
    {
      value: 'go',
      label: 'Go',
      commands: ['go get github.com/JasonXuDeveloper/Nino/runtimes/go/v4'],
      note: generated[lang],
      href: 'advanced/codegen#go',
      link: codegen,
    },
    {
      value: 'rust',
      label: 'Rust',
      commands: [
        'cargo add nino-serialization --features indexmap',
        'cargo add indexmap',
      ],
      note: generated[lang],
      href: 'advanced/codegen#rust',
      link: codegen,
    },
    {
      value: 'typescript',
      label: 'TypeScript',
      commands: ['npm install nino-serialization'],
      note: zh
        ? `${generated.zh}生成的代码默认使用 nino-gen 写在旁边的 nino.ts，设置 Runtime="nino-serialization" 时改为导入这个包。`
        : `${generated.en} Generated code uses the nino.ts written next to it, or this package with Runtime="nino-serialization".`,
      href: 'advanced/codegen#typescript',
      link: codegen,
    },
  ];
}

function CopyButton({ text, lang }: { text: string; lang: Locale }) {
  const [copied, setCopied] = useState(false);
  return (
    <button
      type="button"
      onClick={() => {
        navigator.clipboard?.writeText(text).then(
          () => {
            setCopied(true);
            setTimeout(() => setCopied(false), 1500);
          },
          () => {},
        );
      }}
      className="shrink-0 rounded-md p-1.5 text-fd-muted-foreground transition-colors hover:bg-fd-accent hover:text-fd-accent-foreground"
      aria-label={lang === 'zh' ? '复制命令' : 'Copy the command'}
    >
      {copied ? <Check className="size-4" /> : <Copy className="size-4" />}
    </button>
  );
}

export function HomeInstall({ lang, docs }: { lang: Locale; docs: string }) {
  const zh = lang === 'zh';
  const all = panels(lang);
  const [selected, setSelected] = useState<Platform>('dotnet');
  return (
    <div className="mt-6 flex w-full max-w-xl flex-col items-center">
      <Segmented
        options={all.map(({ value, label }) => ({ value, label }))}
        value={selected}
        onChange={setSelected}
      />
      {all.map((panel) => (
        <div
          key={panel.value}
          role="tabpanel"
          aria-label={panel.label}
          hidden={panel.value !== selected}
          className="w-full text-left"
        >
          <div className="flex items-start gap-2 rounded-lg border bg-fd-secondary/50 py-1.5 pr-1.5 pl-3">
            <pre className="min-w-0 flex-1 py-1 font-mono whitespace-pre-wrap [overflow-wrap:anywhere] text-xs leading-relaxed text-fd-foreground sm:text-sm">
              <code>{panel.commands.join('\n')}</code>
            </pre>
            <CopyButton text={panel.commands.join('\n')} lang={lang} />
          </div>
          <p className="mt-2 text-sm text-fd-muted-foreground">
            {panel.note}{' '}
            <Link
              to={`${docs}/${panel.href}`}
              className="whitespace-nowrap underline underline-offset-4 hover:text-fd-foreground"
            >
              {panel.link}
            </Link>
          </p>
        </div>
      ))}
      <p className="mt-4 flex w-full items-start gap-2 text-left text-sm text-fd-muted-foreground">
        <Bot className="mt-0.5 size-4 shrink-0 text-fd-primary" aria-hidden />
        <span>
          {zh ? 'AI 编程助手：' : 'AI coding agents: '}
          <code className="rounded bg-fd-secondary/50 px-1 py-0.5 font-mono text-xs whitespace-nowrap">
            npx skills add JasonXuDeveloper/Nino
          </code>
          {zh
            ? ' 为 Claude Code、Codex、Cursor、Copilot 等助手安装 nino-serialization skill。'
            : ' installs the nino-serialization skill for Claude Code, Codex, Cursor, Copilot and other agents.'}{' '}
          <Link
            to={`${docs}/start#ai-coding-assistants`}
            className="whitespace-nowrap underline underline-offset-4 hover:text-fd-foreground"
          >
            {zh ? '了解更多' : 'Learn more'}
          </Link>
        </span>
      </p>
    </div>
  );
}
